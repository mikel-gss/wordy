/**
 * Validates the word lists to confirm data integrity.
 * Checks word lengths, character sets, uniqueness, and subset relationship.
 * @returns { valid: boolean, answerCount: number, validCount: number, errors: string[] }
 */
function validateWordLists() {
  const errors = [];
  const regex = /^[a-z]{5}$/;

  // 1. Check ANSWER_WORDS
  const answerSet = new Set();
  for (let i = 0; i < ANSWER_WORDS.length; i++) {
    const w = ANSWER_WORDS[i];
    if (typeof w !== 'string' || w.length !== 5 || !regex.test(w)) {
      errors.push(`Invalid word in ANSWER_WORDS at index ${i}: "${w}"`);
    }
    if (answerSet.has(w)) {
      errors.push(`Duplicate word in ANSWER_WORDS: "${w}"`);
    }
    answerSet.add(w);
  }

  // 2. Check VALID_WORDS
  const validSet = new Set();
  for (let i = 0; i < VALID_WORDS.length; i++) {
    const w = VALID_WORDS[i];
    if (typeof w !== 'string' || w.length !== 5 || !regex.test(w)) {
      errors.push(`Invalid word in VALID_WORDS at index ${i}: "${w}"`);
    }
    if (validSet.has(w)) {
      errors.push(`Duplicate word in VALID_WORDS: "${w}"`);
    }
    validSet.add(w);
  }

  // 3. Confirm all ANSWER_WORDS are present in VALID_WORDS
  for (const w of answerSet) {
    if (!validSet.has(w)) {
      errors.push(`ANSWER_WORDS item not in VALID_WORDS: "${w}"`);
    }
  }

  const isValid = errors.length === 0;

  if (isValid) {
    console.log(
      `%c[Word Lists Validated] ANSWER_WORDS: ${ANSWER_WORDS.length} | VALID_WORDS: ${VALID_WORDS.length} (All checks passed!)`,
      'color: #5DB87A; font-weight: bold;'
    );
  } else {
    console.error(`[Word Lists Validation FAILED] Found ${errors.length} error(s):`, errors);
  }

  return {
    valid: isValid,
    answerCount: ANSWER_WORDS.length,
    validCount: VALID_WORDS.length,
    errors: errors
  };
}

